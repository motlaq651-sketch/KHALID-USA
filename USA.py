def discover_market_movers(min_p, max_p, max_float_m):
    discovered = []
    try:
        url = "https://scanner.tradingview.com/america/scan"
        payload = {
            "filter": [
                {"left": "close", "operation": "in_range", "right": [min_p, max_p]},
                {"left": "volume", "operation": "greater", "right": 50000},
                {"left": "exchange", "operation": "in_range", "right": ["AMEX", "NASDAQ", "NYSE"]},
                {"left": "is_primary", "operation": "equal", "right": True}
            ],
            "options": {"lang": "en"},
            "markets": ["america"],
            "symbols": {"query": {"types": ["stock"]}, "tickers": []},
            "columns": ["name", "close", "change", "volume", "relative_volume_10d_calc", "float_shares_outstanding"],
            "sort": {"sortBy": "relative_volume_10d_calc", "sortOrder": "desc"},
            "range": [0, 30]
        }
        resp = requests.post(url, json=payload, headers={"User-Agent": "Mozilla/5.0"}, timeout=5)
        if resp.status_code == 200:
            for item in resp.json().get("data", []):
                d = item.get("d", [])
                if len(d) >= 6:
                    sym = str(d[0])
                    if not sym.isalpha() or len(sym) > 5:
                        continue
                    fl_shares = d[5]
                    fl_m = round(fl_shares / 1e6, 2) if fl_shares and fl_shares > 0 else 8.5
                    if fl_m <= max_float_m:
                        st.session_state.float_cache[sym] = fl_m
                        discovered.append(sym)
                        if len(discovered) >= 12:
                            break
    except Exception:
        pass
    combined = []
    for s in discovered + BASE_WATCHLIST:
        if s not in combined:
            combined.append(s)
    return combined[:18]

