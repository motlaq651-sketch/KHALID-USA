def compute_trade_plan(res, capital, risk_pct, buffer_pct, split_e1):
    entry1 = res['entry1']
    s1 = res['s1']
    entry2 = round(s1 + (entry1 - s1) * 0.20, 4)
    safe_stop = round(s1 * (1 - (buffer_pct / 100.0)), 4)

    w1 = split_e1 / 100.0
    w2 = 1.0 - w1
    avg_entry = round((entry1 * w1) + (entry2 * w2), 4) if w2 > 0 else entry1
    risk_per_share = max(avg_entry - safe_stop, 0.0001)

    total_shares = int((capital * (risk_pct / 100.0)) / risk_per_share)
    if total_shares * avg_entry > capital:
        total_shares = int(capital / max(avg_entry, 0.0001))

    shares_e1 = int(total_shares * w1)
    shares_e2 = total_shares - shares_e1
    actual_loss_usd = round(total_shares * risk_per_share, 2)
    target1 = round(avg_entry + (risk_per_share * 1.5), 4)
    target2 = round(avg_entry + (risk_per_share * 2.5), 4)
    profit_t1 = round(total_shares * (target1 - avg_entry), 2)
    stop_pct = round(((avg_entry - safe_stop) / max(avg_entry, 0.0001)) * 100, 2)

    return {
        "entry2": entry2, "safe_stop": safe_stop, "avg_entry": avg_entry,
        "shares_e1": shares_e1, "shares_e2": shares_e2, "total_shares": total_shares,
        "actual_loss_usd": actual_loss_usd, "target1": target1, "target2": target2,
        "profit_t1": profit_t1, "stop_pct": stop_pct
    }

def get_entry_recommendation(res, plan, min_p, max_p, max_fl):
    matches_user_filters = (min_p <= res['entry1'] <= max_p) and (res['float_m'] <= max_fl)
    if not matches_user_filters:
        return "❌ لا ينصح للشراء (خارج نطاق السعر/الفلوت المحدد)"
    if plan['total_shares'] <= 0:
        return "❌ لا ينصح للشراء (رأس المال/المخاطرة لا تكفي)"
    if res['inst_flow'] < -20 or res['dist_pct'] >= 55:
        return "❌ لا ينصح للشراء (مرصود تصريف مؤسسي واضح)"
    if res['sweep_val'] == -1 and res['dist_pct'] >= 35:
        return "⚠️ احذر الشراء الآن (مصيدة قمة وسحب سيولة علوي)"
    if res['alert_level'] == 2:
        return "✅ ينصح للشراء الآن (مطابق لشروط المؤسسات)"
    elif res['alert_level'] == 1:
        if res['rsi'] > 75 or res['mfi'] > 80:
            return "⚠️ لا ينصح للشراء الفوري (انتظر تهدئة RSI/MFI)"
        return "✅ ينصح للشراء التدريجي (دعم مؤسسي نشط)"
    else:
        if res['sweep_val'] == 1 and res['inst_flow'] >= 10:
            return "✅ فرصة ارتداد بعد سحب سيولة سفلي ودعم مؤسسي"
        return "❌ لا ينصح للشراء حالياً (ضعف السيولة)"

