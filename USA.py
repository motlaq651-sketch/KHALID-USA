def format_vol(num):
    num = float(num or 0)
    sign = "-" if num < 0 else ""
    num_abs = abs(num)
    if num_abs >= 1_000_000:
        return f"{sign}{num_abs/1_000_000:.2f}M"
    elif num_abs >= 1_000:
        return f"{sign}{num_abs/1_000:.1f}K"
    return f"{sign}{int(num_abs):,}"

