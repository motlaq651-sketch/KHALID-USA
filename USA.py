    times = day_df.index.time

    pre_market_vol = int(day_df.loc[times < dtime(9, 30), 'Volume'].sum())
    regular_market_vol = int(day_df.loc[(times >= dtime(9, 30)) & (times < dtime(16, 0)), 'Volume'].sum())
    after_hours_vol = int(day_df.loc[times >= dtime(16, 0), 'Volume'].sum())
    total_day_vol = pre_market_vol + regular_market_vol + after_hours_vol

    df_et['EMA9'] = df_et['Close'].ewm(span=9, adjust=False).mean()
    df_et['EMA20'] = df_et['Close'].ewm(span=20, adjust=False).mean()
    df_et['EMA50'] = df_et['Close'].ewm(span=50, adjust=False).mean()
    df_et['EMA200'] = df_et['Close'].ewm(span=200, adjust=False).mean()

    tp = (df_et['High'] + df_et['Low'] + df_et['Close']) / 3.0
    pv = tp * df_et['Volume']
    df_et['VWAP'] = pv.groupby(df_et.index.date).cumsum() / df_et['Volume'].replace(0, 1).groupby(df_et.index.date).cumsum()

    active_vols = df_et['Volume'].replace(0, np.nan).ffill().fillna(1.0)
    df_et['Vol_MA'] = active_vols.rolling(window=10, min_periods=1).mean()

    # مؤشر RSI 14
    delta = df_et['Close'].diff()
    gain = delta.clip(lower=0)
    loss = -1 * delta.clip(upper=0)
    avg_gain = gain.ewm(alpha=1/14, min_periods=14, adjust=False).mean()
    avg_loss = loss.ewm(alpha=1/14, min_periods=14, adjust=False).mean()
    rs = avg_gain / avg_loss.replace(0, 1e-9)
    df_et['RSI'] = (100 - (100 / (1 + rs))).fillna(50.0)

    # مؤشر السيولة MFI 14
    tp_diff = tp.diff()
    pos_mf = pd.Series(np.where(tp_diff > 0, pv, 0.0), index=df_et.index)
    neg_mf = pd.Series(np.where(tp_diff < 0, pv, 0.0), index=df_et.index)
    pos_mf_14 = pos_mf.rolling(window=14, min_periods=1).sum()
    neg_mf_14 = neg_mf.rolling(window=14, min_periods=1).sum()
    mfr = pos_mf_14 / neg_mf_14.replace(0, 1e-9)
    df_et['MFI'] = (100 - (100 / (1 + mfr))).fillna(50.0)

    # مؤشر OBV ومتوسطه
    obv_dir = np.where(df_et['Close'] > df_et['Close'].shift(1), 1, np.where(df_et['Close'] < df_et['Close'].shift(1), -1, 0))
    df_et['OBV'] = (obv_dir * df_et['Volume']).cumsum()
    df_et['OBV_EMA'] = df_et['OBV'].ewm(span=10, adjust=False).mean()

    # مؤشر ستوكاستيك Stochastic (14, 3, 3)
    low_14 = df_et['Low'].rolling(window=14, min_periods=1).min()
    high_14 = df_et['High'].rolling(window=14, min_periods=1).max()
    stoch_denom = (high_14 - low_14).replace(0, 1e-9)
    stoch_k_raw = 100.0 * ((df_et['Close'] - low_14) / stoch_denom)
    df_et['Stoch_K'] = stoch_k_raw.rolling(window=3, min_periods=1).mean().fillna(50.0)
    df_et['Stoch_D'] = df_et['Stoch_K'].rolling(window=3, min_periods=1).mean().fillna(50.0)

    # =========================================================================
    # مؤشرات سحب السيولة، دخول المؤسسات، والتصريف الاحترافية (Smart Money & VSA)
    # =========================================================================
    candle_range = (df_et['High'] - df_et['Low']).replace(0, 1e-9)
    close_pos = (df_et['Close'] - df_et['Low']) / candle_range
    upper_wick_ratio = (df_et['High'] - df_et[['Open', 'Close']].max(axis=1)) / candle_range
    lower_wick_ratio = (df_et[['Open', 'Close']].min(axis=1) - df_et['Low']) / candle_range
